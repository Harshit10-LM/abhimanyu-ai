"""Non-blocking code optimizer for Arduino / C++ firmware.

Inspired by AI.duino. Identifies blocking delay() loops and refactors them
into responsive millis()-based state machines with educational explanations.
"""

from dataclasses import dataclass
import re
from typing import Optional, Tuple


@dataclass
class OptimizationResult:
    """Outcome of non-blocking firmware refactoring."""

    is_optimizable: bool
    original_code: str
    optimized_code: str
    explanation: str
    delay_values_ms: list[int]


class NonBlockingOptimizer:
    """Transforms blocking delay() patterns into responsive millis() state machines."""

    @staticmethod
    def analyze_and_optimize(source_code: str) -> OptimizationResult:
        """Inspects source code for delay() in loop() and generates non-blocking code."""
        # Find delay calls
        delays = re.findall(r"\bdelay\s*\(\s*(\d+)\s*\)", source_code)
        delay_vals = [int(d) for d in delays]

        if not delay_vals or "void loop()" not in source_code:
            return OptimizationResult(
                is_optimizable=False,
                original_code=source_code,
                optimized_code=source_code,
                explanation="No blocking delay() calls detected inside loop(). The code is already non-blocking or event-driven.",
                delay_values_ms=[],
            )

        interval = delay_vals[0] if delay_vals else 1000

        # Check for classic blink pattern
        is_blink_pattern = (
            "digitalWrite" in source_code
            and "HIGH" in source_code
            and "LOW" in source_code
            and len(delay_vals) >= 1
        )

        # Generate educational explanation
        explanation = (
            f"Detected blocking delay({interval}) calls inside loop(). "
            "Calling delay() pauses the microcontroller entirely for that duration, preventing it from "
            "responding to button presses, reading sensors, or processing serial communication. "
            "Refactoring to a non-blocking millis() timer checks elapsed time without halting CPU execution, "
            "allowing loop() to execute continuously."
        )

        # Detect pin if possible
        pin_match = re.search(r"digitalWrite\s*\(\s*([A-Za-z0-9_]+)\s*,\s*HIGH\s*\)", source_code)
        pin_token = pin_match.group(1) if pin_match else "LED_PIN"

        # Generate non-blocking code
        if is_blink_pattern:
            optimized_code = f"""// Non-blocking refactored sketch using millis()
// Generated by Firmware-Alchemist Non-Blocking Optimizer

#define {pin_token} {pin_token if not pin_token.isdigit() else pin_token}

unsigned long previousMillis = 0;
const unsigned long interval = {interval}; // Interval in milliseconds
bool ledState = false;

void setup() {{
  pinMode({pin_token}, OUTPUT);
}}

void loop() {{
  unsigned long currentMillis = millis();

  // Check if the timer interval has elapsed without blocking the CPU
  if (currentMillis - previousMillis >= interval) {{
    previousMillis = currentMillis;
    ledState = !ledState; // Toggle state
    digitalWrite({pin_token}, ledState ? HIGH : LOW);
  }}

  // The microcontroller can now perform other tasks here simultaneously!
}}
"""
        else:
            # Generic non-blocking wrapper
            loop_body = re.search(r"void\s+loop\s*\(\s*\)\s*\{([\s\S]*)\}", source_code)
            body_content = loop_body.group(1).strip() if loop_body else "// sketch logic"
            clean_body = re.sub(r"delay\s*\(\s*\d+\s*\);\s*", "", body_content)

            optimized_code = f"""// Non-blocking refactored sketch using millis()
unsigned long previousMillis = 0;
const unsigned long interval = {interval};

void setup() {{
  // Setup configuration preserved
}}

void loop() {{
  unsigned long currentMillis = millis();

  if (currentMillis - previousMillis >= interval) {{
    previousMillis = currentMillis;
    // Execute periodic timed task:
    {clean_body}
  }}

  // Non-blocking execution allows immediate handling of other I/O here
}}
"""

        return OptimizationResult(
            is_optimizable=True,
            original_code=source_code,
            optimized_code=optimized_code,
            explanation=explanation,
            delay_values_ms=delay_vals,
        )

